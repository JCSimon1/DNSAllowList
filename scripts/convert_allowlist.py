from pathlib import Path
import re
import sys


SOURCE = Path("Allow-list")
TARGET = Path("Allow-list-AdGuard")


REGEX_ESCAPE = re.compile(
    r"""\\[dDsSwWbBAZzfnrtv]|\\[.^$*+?{}\[\]()]"""
)


def is_regex(rule: str) -> bool:
    rule = rule.strip()

    # Explicit /regex/ syntax
    if len(rule) >= 2 and rule.startswith("/") and rule.endswith("/"):
        return True

    # Anchored regex
    if rule.startswith("^") or rule.endswith("$"):
        return True

    # Common regex escapes such as:
    # \d \D \s \w \. \( \)
    if REGEX_ESCAPE.search(rule):
        return True

    return False


def convert_regex(rule: str) -> str:
    rule = rule.strip()

    # Remove /.../ wrapper if present
    if len(rule) >= 2 and rule.startswith("/") and rule.endswith("/"):
        rule = rule[1:-1]

    return f"@@/{rule}/$important"


def convert_domain(rule: str) -> str:
    rule = rule.strip().rstrip(".")

    # Remove surrounding whitespace
    rule = rule.strip()

    # Handle:
    # südkurier (xn--sdkurier-65a)
    #
    # If a parenthesized punycode hostname is provided,
    # use the DNS-compatible representation.
    match = re.fullmatch(
        r".+\((xn--[A-Za-z0-9-]+)\)",
        rule,
        flags=re.IGNORECASE,
    )

    if match:
        rule = match.group(1)

    # Convert Unicode hostnames to IDNA where possible.
    try:
        rule = rule.encode("idna").decode("ascii")
    except UnicodeError:
        pass

    return f"@@||{rule}^"


def split_comment(line: str):
    """
    Split an allow-list line into:

        rule
        comment

    Example:

        amd.com # AMD website

    becomes:

        amd.com
        # AMD website
    """

    match = re.search(r"\s+#", line)

    if not match:
        return line.strip(), ""

    rule = line[:match.start()].strip()
    comment = line[match.start():].strip()

    return rule, comment


def main():
    if not SOURCE.exists():
        print(f"ERROR: Source file not found: {SOURCE}")
        sys.exit(1)

    lines = SOURCE.read_text(encoding="utf-8").splitlines()

    output = []

    output.append("# AdGuard Home DNS allowlist")
    output.append("#")
    output.append("# THIS FILE IS AUTOMATICALLY GENERATED.")
    output.append("# DO NOT EDIT THIS FILE MANUALLY.")
    output.append("#")
    output.append("# Source:")
    output.append(
        "# https://github.com/JCSimon1/DNSAllowList/blob/main/Allow-list"
    )
    output.append("")

    domain_count = 0
    regex_count = 0
    comment_count = 0
    empty_count = 0
    errors = []

    for line_number, original_line in enumerate(lines, start=1):

        stripped = original_line.strip()

        # Empty lines
        if not stripped:
            output.append("")
            empty_count += 1
            continue

        # Full-line comments
        if stripped.startswith("#") or stripped.startswith("!"):
            output.append(original_line)
            comment_count += 1
            continue

        rule, comment = split_comment(original_line)

        if not rule:
            output.append(original_line)
            continue

        try:

            if is_regex(rule):
                converted = convert_regex(rule)
                regex_count += 1
            else:
                converted = convert_domain(rule)
                domain_count += 1

            if comment:
                output.append(f"{converted} {comment}")
            else:
                output.append(converted)

        except Exception as exc:
            errors.append(
                f"Line {line_number}: {original_line!r} -> {exc}"
            )

    if errors:
        print("ERROR: Conversion failed.\n")

        for error in errors:
            print(error)

        sys.exit(1)

    TARGET.write_text(
        "\n".join(output) + "\n",
        encoding="utf-8",
    )

    print("Conversion successful.")
    print()
    print(f"Input lines:      {len(lines)}")
    print(f"Domain rules:     {domain_count}")
    print(f"Regex rules:      {regex_count}")
    print(f"Comments:         {comment_count}")
    print(f"Empty lines:      {empty_count}")
    print()
    print(f"Generated:        {TARGET}")


if __name__ == "__main__":
    main()